EXPECTED_MODELS = ["B01", "B02", "B03", "H00", "H01", "H02", "H01_sec"]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=REPO)
    args = parser.parse_args(argv)
    repo = args.repo_root

    results: list[dict] = []

    def record(name: str, status: str, detail: str = "") -> None:
        results.append({"check": name, "status": status, "detail": detail})
        line = f"[{status:7s}] {name}" + (f" - {detail}" if detail else "")
        try:
            print(line)
        except UnicodeEncodeError:
            print(line.encode("ascii", "replace").decode("ascii"))

    # 1. Frozen file: existence + exact SHA-256 (verbatim rule).
    frozen = repo / "artifacts/test/frozen_evaluation.json"
    if not frozen.is_file():
        record("frozen file exists", "FAIL", "artifacts/test/frozen_evaluation.json not found")
    elif sha256_file(frozen) == FROZEN_FILE_SHA256:
        record("frozen file sha256", "PASS", FROZEN_FILE_SHA256[:12] + "…")
    else:
        record("frozen file sha256", "FAIL",
               f"got {sha256_file(frozen)[:12]}…, expected {FROZEN_FILE_SHA256[:12]}… (DO NOT MODIFY)")

    # 2. Frozen internal consistency.
    try:
        frozen_data = json.loads(frozen.read_text(encoding="utf-8"))
        if frozen_data.get("test_split_sha256") == TEST_SPLIT_SHA256:
            record("frozen test_split_sha256", "PASS", "440-image canonical test split")
        else:
            record("frozen test_split_sha256", "FAIL", "mismatch vs locked test split")
        ck = frozen_data.get("checkpoints", {})
        ok = (ck.get("B01_yolo11n", {}).get("sha256", "").startswith("c0cfe917")
              and ck.get("B02_yolo11s", {}).get("sha256", "").startswith("aa079248")
              and ck.get("B03_efficientad_s", {}).get("sha256", "").startswith("9453bc2c"))
        record("frozen checkpoint SHAs", "PASS" if ok else "FAIL",
               "B01/B02/B03 entries" if ok else "checkpoint entries mismatch")
        ops = frozen_data.get("operating_points", {})
        ok_ops = (ops.get("H01", {}).get("tau_yolo") == 0.14
                  and ops.get("H01", {}).get("tau_ad") == 1.4598
                  and ops.get("H01_sec", {}).get("tau_yolo") == 0.48)
        record("frozen operating points", "PASS" if ok_ops else "FAIL",
               "H01 0.14/1.4598, H01_sec 0.48" if ok_ops else "threshold mismatch")
    except (OSError, ValueError) as exc:
        record("frozen content parse", "FAIL", str(exc)[:200])

    # 3. Checkpoints: existence + SHA-256 (MISSING is honest, not PASS).
    for label, (rel, expected) in CHECKPOINTS.items():
        path = repo / rel
        if not path.is_file():
            record(f"checkpoint {label}", "MISSING",
                   f"{rel} absent (git-ignored); restore from checkpoint handoff, then re-run")
        elif sha256_file(path) == expected:
            record(f"checkpoint {label}", "PASS", expected[:12] + "…")
        else:
            record(f"checkpoint {label}", "FAIL",
                   f"hash mismatch — possible corruption, do not use for inference")

    # 4. Artifact metadata cross-check (tracked JSON sidecars).
    for rel, (field, expected) in CONFIG_HASHES.items():
        path = repo / rel
        if not path.is_file():
            record(f"sidecar {rel}", "FAIL", "tracked file missing from git checkout")
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            record(f"sidecar {rel}", "PASS" if data.get(field) == expected else "FAIL",
                   f"{field} matches" if data.get(field) == expected else "hash field mismatch")
        except ValueError as exc:
            record(f"sidecar {rel}", "FAIL", str(exc)[:200])

    # 5. Required files (tracked; must exist).
    for rel in REQUIRED_FILES:
        path = repo / rel
        if path.is_file():
            record(f"file {rel}", "PASS", f"{path.stat().st_size} bytes")
        else:
            record(f"file {rel}", "FAIL", "expected tracked file not found")

    # 6. Benchmark CSV content: 7 models, sane metric ranges.
    summary = repo / "artifacts/test/benchmark_summary.csv"
    if summary.is_file():
        try:
            rows = list(csv.DictReader(summary.read_text(encoding="utf-8").splitlines()))
            ids = [r["model_id"] for r in rows]
            if ids == EXPECTED_MODELS:
                record("benchmark models", "PASS", "B01/B02/B03/H00/H01/H02/H01_sec")
            else:
                record("benchmark models", "FAIL", f"got {ids}")
            sane = all(0.0 <= float(r["balanced_accuracy"]) <= 1.0
                       and 0.0 <= float(r["frr"]) <= 1.0 for r in rows)
            record("benchmark ranges", "PASS" if sane else "FAIL",
                   "BalAcc/FRR in [0,1]" if sane else "metric out of range")
            h01 = next((r for r in rows if r["model_id"] == "H01"), None)
            if h01 and abs(float(h01["balanced_accuracy"]) - 0.95) < 1e-9:
                record("benchmark H01 spot-check", "PASS", "BalAcc 0.95, recall 1.0")
            else:
                record("benchmark H01 spot-check", "FAIL", "H01 row mismatch vs locked report")
        except (ValueError, KeyError) as exc:
            record("benchmark content", "FAIL", str(exc)[:200])

    # 7. Runtime parity reports: Delta < 1e-3 and 0 flips where exported.
    for model in ("B01", "B03", "H00", "H01"):
        rep = repo / f"artifacts/runtime/{model}/export_report.json"
        if not rep.is_file():
            continue  # already covered by REQUIRED_FILES
        try:
            data = json.loads(rep.read_text(encoding="utf-8"))
            parity = data.get("parity", {}).get("parity", {})
            if not parity:
                record(f"parity {model}", "FAIL", "export_report.json has no parity section")
                continue
            passed = parity.get("passed", False)
            record(f"parity {model}", "PASS" if passed else "FAIL",
                   f"maxDelta={parity.get('score_delta_max', '?')}, "
                   f"matches={parity.get('decision_matches', '?')}/{data.get('parity', {}).get('total', '?')}")
        except ValueError as exc:
            record(f"parity {model}", "FAIL", str(exc)[:200])

    n_pass = sum(1 for r in results if r["status"] == "PASS")
    n_fail = sum(1 for r in results if r["status"] == "FAIL")
    n_missing = sum(1 for r in results if r["status"] == "MISSING")
    print(f"\n[verify] {n_pass} PASS, {n_fail} FAIL, {n_missing} MISSING / {len(results)} checks")
    if n_missing:
        print("[verify] MISSING checkpoints: restore .pt files from the checkpoint handoff "
              "(see docs/REPRODUCIBILITY.md §2), then re-run this script.")
    return 0 if (n_fail == 0 and n_missing == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
